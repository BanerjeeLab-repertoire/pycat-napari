"""Run the real-data harness and write ``docs/pipeline_route_matrix.md`` (Completion Spec Phase 0.3).

    python tools/route_matrix.py            # run every pipeline x route, write the matrix
    python tools/route_matrix.py --repin    # ... and re-pin the golden masters (tests/data/golden_tables.json)

Re-pinning changes what counts as correct: do it only for a deliberate change, with a CHANGELOG line saying why.
"""
from __future__ import annotations

import argparse
import json
import platform
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
MATRIX = ROOT / 'docs' / 'pipeline_route_matrix.md'
_ICON = {'pass': 'pass', 'fail': '**FAIL**', 'not-implemented': 'not-impl.', 'not-applicable': 'n/a',
         'no-data': 'no data'}


def render(matrix: dict) -> str:
    import tomllib
    from tests.data.fetch import entries
    from tests.realdata_harness import CASES, ROUTES, SIG_DIGITS
    lines = ['# Pipeline × route matrix (real data)', '',
             f'Generated by `tools/route_matrix.py` on {date.today().isoformat()} — PyCAT '
             f'{tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]["version"]}, Python {platform.python_version()}, {platform.system()}. '
             'Do not edit by hand.', '',
             'Each pipeline runs its recorded config on its corpus file (`tests/data/registry.txt`). '
             '**batch** = the config through the real batch runner on the file; **headless** = the toolbox '
             'called directly, compared with batch; **session** = the batch table saved and restored with the '
             'real session writer; **kernel** = `OperationService`. Verdicts: pass / FAIL / not-impl. / n/a / '
             f'no data — never blank. Golden masters pin each table at {SIG_DIGITS} significant digits.', '',
             '| pipeline | ' + ' | '.join(ROUTES) + ' | batch time | linking |', '|' + '---|' * (len(ROUTES) + 3)]
    for case in CASES:
        v = matrix[case.pipeline]
        cells = [_ICON[v[r].verdict] for r in ROUTES]
        t = v['batch'].seconds
        lines.append(f'| {case.pipeline} | ' + ' | '.join(cells) + f" | {'' if t != t else f'{t:.1f} s'} | "
                     + (f'n/a ({case.not_applicable})' if case.not_applicable else 'objects') + ' |')
    lines += ['', '## Why each cell is what it is', '']
    for case in CASES:
        lines.append(f'**{case.pipeline}**' + (f' — `{case.corpus}`' if case.corpus else ''))
        for r in ROUTES:
            v = matrix[case.pipeline][r]
            lines.append(f'- {r}: {v.verdict}' + (f' — {v.reason}' if v.reason else '')
                         + (f' (golden `{v.digest}`)' if v.digest else ''))
        lines.append('')
    lines += ['## Negative fixtures', '', '| role | file | provenance |', '|---|---|---|']
    for e in entries():
        if e.pipeline.startswith('neg:'):
            lines.append(f"| {e.pipeline[4:]} | {e.filename} | {e.provenance.get('transform', '')} |")
    return '\n'.join(lines) + '\n'


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--repin', action='store_true')
    args = ap.parse_args(argv)
    from tests.realdata_harness import GOLDEN, run_matrix
    matrix = run_matrix()
    if args.repin:
        pins = {p: v['batch'].digest for p, v in matrix.items() if v['batch'].digest}
        GOLDEN.write_text(json.dumps(pins, indent=2, sort_keys=True) + '\n', encoding='utf-8')
        print(f're-pinned {len(pins)} golden masters -> {GOLDEN.relative_to(ROOT)}')
        matrix = run_matrix()
    MATRIX.write_text(render(matrix), encoding='utf-8', newline='\n')
    print(f'wrote {MATRIX.relative_to(ROOT)}')
    for p, v in matrix.items():
        print(f'  {p:26s} ' + '  '.join(f'{r}={v[r].verdict}' for r in v))
    return 0


if __name__ == '__main__':
    sys.exit(main())
